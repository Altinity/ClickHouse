#!/usr/bin/env python3
"""gen_override.py BINARY [EXTRA_CONFIG_XML]: write a compose override that mounts BINARY (and one extra config.d file) into the stand.

The override goes to $GC_AB_OUT/override-current.yml (default: the current directory).
"""
import os
import sys

binary = sys.argv[1]
extra = sys.argv[2] if len(sys.argv) > 2 else ""
out = ["# generated by gen_override.py", "services:"]
for svc in ("keeper1", "ch1", "ch2"):
    out += [f"  {svc}:", "    volumes:", f"      - {binary}:/usr/bin/clickhouse:ro"]
    if extra and svc != "keeper1":
        out.append(f"      - {extra}:/etc/clickhouse-server/config.d/zz_gc_extra.xml:ro")
out_dir = os.environ.get("GC_AB_OUT") or os.getcwd()
open(os.path.join(out_dir, "override-current.yml"), "w").write("\n".join(out) + "\n")
